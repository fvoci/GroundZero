"""Generate the six approved Noto derivatives, CSS ranges and hash manifest."""

import argparse
import importlib.metadata
import io
import json
from pathlib import Path
import subprocess
import tempfile

from fontTools import subset
from fontTools.ttLib import TTFont, woff2

from font_assets import (BASE, FONT_DIR, ORIGINALS, common_points, name_metadata,
                         sha256, source_bytes, unicode_points, verify_assets, verify_css)


def unicode_ranges(points):
    ranges = []
    for point in sorted(points):
        if ranges and ranges[-1][1] + 1 == point:
            ranges[-1][1] = point
        else:
            ranges.append([point, point])
    return ', '.join(f'U+{a:X}' if a == b else f'U+{a:X}-{b:X}' for a, b in ranges)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='regenerate without replacing committed files')
    args = parser.parse_args()
    versions = {'fonttools': '4.60.1', 'Brotli': '1.2.0'}
    for package, version in versions.items():
        assert importlib.metadata.version(package) == version, package
    assets = []
    css = ['/* Generated by tools/generate-fonts.sh (D-86). Do not edit. */']
    with tempfile.TemporaryDirectory(dir='target', prefix='fonts-generate-') as temporary:
        generated = Path(temporary)
        for name in ORIGINALS:
            data = source_bytes(name)
            if name.startswith('D2Coding'):
                assert (FONT_DIR / name).read_bytes() == data, 'D2Coding must stay original'
                (generated / name).write_bytes(data)
                assets.append({'file': name, 'sha256': sha256(data), 'bytes': len(data), 'original': name})
                continue
            if name.startswith('NotoSerif'):
                output = generated / (Path(name).stem + '.woff2')
                woff2.compress(io.BytesIO(data), output, transform_tables=set())
                assets.append({'file': output.name, 'sha256': sha256(output.read_bytes()),
                               'bytes': output.stat().st_size, 'original': name})
                continue
            with TTFont(io.BytesIO(data), recalcTimestamp=False) as original:
                expected_metadata = name_metadata(original)
                for _, _, _, _, value in expected_metadata:
                    assert b'Reserved Font Name' not in value.replace(b'\x00', b''), 'RFN in subset input'
                common = common_points(original)
                selectors = {selector for table in original['cmap'].tables if table.format == 14
                             for selector in table.uvsDict}
                for piece, points in [('common', common), ('rest', unicode_points(original) - common)]:
                    output = generated / (Path(name).stem + f'-{piece}.woff2')
                    font = TTFont(io.BytesIO(data), recalcTimestamp=False)
                    options = subset.Options()
                    options.layout_features = ['*']
                    options.layout_scripts = ['*']
                    options.name_IDs = ['*']
                    options.name_languages = ['*']
                    options.name_legacy = True
                    options.legacy_cmap = True
                    options.symbol_cmap = True
                    options.notdef_outline = True
                    options.recommended_glyphs = True
                    options.glyph_names = True
                    worker = subset.Subsetter(options=options)
                    worker.populate(unicodes=points | selectors)
                    worker.subset(font)
                    assert name_metadata(font) == expected_metadata, 'name metadata changed'
                    font.flavor = 'woff2'
                    font.flavorData = woff2.WOFF2FlavorData(transformedTables=set())
                    font.save(output, reorderTables=False)
                    font.close()
                    assets.append({'file': output.name, 'sha256': sha256(output.read_bytes()),
                                   'bytes': output.stat().st_size, 'original': name,
                                   'unicode_count': len(points)})
                    weight = 400 if 'Regular' in name else 700
                    css.extend([
                        '@font-face {', "  font-family: 'Noto Sans KR';",
                        f'  font-weight: {weight};', '  font-display: swap;',
                        f"  src: url('../assets/fonts/{output.name}') format('woff2');",
                        f'  unicode-range: {unicode_ranges(points)};', '}',
                    ])
        verify_assets(generated)
        manifest = {
            'source_commit': BASE, 'tools': versions,
            'originals': [{'file': name, 'sha256': digest} for name, digest in ORIGINALS.items()],
            'assets': assets,
        }
        files = {FONT_DIR / asset['file']: (generated / asset['file']).read_bytes()
                 for asset in assets if asset['file'].endswith('.woff2')}
        css_path = Path('apps/web/src/styles/font-ranges.css')
        files[css_path] = subprocess.run(
            ['pnpm', 'exec', 'prettier', '--stdin-filepath', str(css_path)],
            input=('\n'.join(css) + '\n').encode(), capture_output=True, check=True,
        ).stdout
        verify_css(files[css_path].decode(), generated)
        files[Path('tools/font-assets.json')] = (json.dumps(manifest, indent=2) + '\n').encode()
        if args.check:
            for path, content in files.items():
                assert path.read_bytes() == content, f'non-reproducible artifact: {path}'
        else:
            for path, content in files.items():
                path.write_bytes(content)
            for name in ORIGINALS:
                if name.startswith('Noto'):
                    (FONT_DIR / name).unlink(missing_ok=True)
    verify_assets()
    print('PASS deterministic Noto generation and D-86 asset verification')


if __name__ == '__main__':
    main()
