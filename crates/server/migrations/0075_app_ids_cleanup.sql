-- 앱이 만든 id로 옮기기의 마무리(D-88, 0070 머리말). 0070~0074가 모든 호출을 새 서명으로 옮겼다.
--
-- 1. 옛 서명(앱이 id를 넘기지 않던 것)을 지운다. 이후 그 서명으로 부르면 함수가 없다는 오류가 난다.
-- 2. 표의 id 기본값을 지운다. 새 설치는 처음 만드는 마이그레이션에 기본값이 없고, 이 문장은 그 전에 만든 설치를
--    같은 상태로 맞춘다(기본값이 없으면 아무것도 하지 않는다). id 없이 넣으면 NOT NULL 위반으로 멈춘다.
-- 3. id가 UUIDv7인지 표에서도 확인한다(앱 함수의 `app_id`와 같은 규칙. 다른 판의 UUID로 대신 채우지 못하게).

