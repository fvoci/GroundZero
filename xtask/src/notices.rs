//! 제3자 고지(`THIRD_PARTY_NOTICES.txt`) 생성·확인. 배포물(제품 이미지의 서버 바이너리와 웹 번들)에 실제로 들어가는
//! 패키지만 담는다(D-60).
//!
//! - Rust: `cargo metadata`(x86_64-unknown-linux-gnu 기준)에서 fvoci-server의 일반 의존성을 따라간다. 빌드·개발
//!   의존성과 컴파일 때만 실행되는 proc-macro는 바이너리에 들지 않아 뺀다.
//! - npm: 운영 웹 빌드를 소스맵과 함께 임시 디렉터리에 만들고 소스맵에 든 패키지만 담는다. CSS에 `@import`로 들어오는
//!   패키지(`apps/web/src/styles/app.css`)를 더한다. 의존성 종류(직접·개발)만으로 배포 여부를 정하지 않는다.
//!
//! 각 패키지가 함께 배포하는 LICENSE·NOTICE·COPYING 파일을 그대로 싣고, 그런 파일이 없으면 SPDX 원문을 부록에 싣는다.

use std::collections::BTreeSet;
use std::fs;
use std::path::{Path, PathBuf};

use anyhow::{Context, Result, bail};
use serde_json::Value;
use xshell::{Shell, cmd};

const OUTPUT: &str = "THIRD_PARTY_NOTICES.txt";
const SERVER_TARGET: &str = "x86_64-unknown-linux-gnu";

#[derive(Debug)]
struct Package {
    name: String,
    version: String,
    license: String,
    repository: String,
    /// 이 판의 소스 묶음 주소(레지스트리). 파일 단위 카피레프트(MPL-2.0)는 소스 입수 경로를 함께 알린다(D-74).
    archive: String,
    texts: Vec<(String, String)>,
}

pub fn run(root: &Path, check: bool) -> Result<()> {
    let rendered = render(root)?;
    let path = root.join(OUTPUT);
    if check {
        let current = fs::read_to_string(&path).unwrap_or_default();
        if current != rendered {
            bail!("{OUTPUT} is out of date; run `cargo xtask notices`");
        }
        println!("{OUTPUT} up to date");
    } else {
        fs::write(&path, rendered).with_context(|| format!("write {OUTPUT}"))?;
        println!("wrote {OUTPUT}");
    }
    Ok(())
}

fn render(root: &Path) -> Result<String> {
    let crates = rust_packages(root)?;
    let npm = npm_packages(root)?;
    let mut out = String::new();
    out.push_str("fvoci third-party notices / 제3자 고지\n");
    out.push_str("Generated by `cargo xtask notices`. Do not edit by hand.\n");
    out.push_str(
        "Covers what ships in the product image: the server binary (Rust crates linked for ",
    );
    out.push_str(SERVER_TARGET);
    out.push_str(") and the web bundle (npm packages found in the production build).\n\n");
    let mut missing: BTreeSet<String> = BTreeSet::new();
    section(
        &mut out,
        "Rust crates (server binary)",
        &crates,
        &mut missing,
    );
    section(&mut out, "npm packages (web bundle)", &npm, &mut missing);
    // HWP·HWPX 미리보기 WASM(D-76)의 크레이트. `cargo xtask rhwp`가 그 빌드에서 만든 고지를 그대로 싣는다.
    let rhwp = fs::read_to_string(root.join(crate::rhwp::NOTICES))
        .with_context(|| format!("read {} (run `cargo xtask rhwp`)", crate::rhwp::NOTICES))?;
    let body = rhwp.split_once('\n').map_or("", |(_, rest)| rest);
    out.push_str(
        "==================== Rust crates (HWP/HWPX preview WebAssembly) ====================\n\n",
    );
    out.push_str(body);
    out.push('\n');
    fonts(root, &mut out)?;
    if !missing.is_empty() {
        out.push_str("==================== Appendix: SPDX license texts ====================\n\n");
        out.push_str("For packages above that do not ship their own license file.\n\n");
        for id in &missing {
            let Some(license) = spdx::license_id(id) else {
                continue;
            };
            out.push_str(&format!(
                "---- {id} ----\n\n{}\n\n",
                normalize(license.text())
            ));
        }
    }
    Ok(out)
}

fn section(out: &mut String, title: &str, packages: &[Package], missing: &mut BTreeSet<String>) {
    out.push_str(&format!(
        "==================== {title}: {} ====================\n\n",
        packages.len()
    ));
    for p in packages {
        out.push_str(&format!("---- {} {} ----\n", p.name, p.version));
        out.push_str(&format!("License: {}\n", p.license));
        if !p.repository.is_empty() {
            out.push_str(&format!("Source: {}\n", p.repository));
        }
        if spdx_ids(&p.license).iter().any(|id| id.starts_with("MPL-")) {
            out.push_str(&format!(
                "Source code of this version (MPL-2.0 section 3.2): {}\n",
                p.archive
            ));
        }
        out.push('\n');
        if p.texts.is_empty() {
            out.push_str("(No license file shipped with the package; see the SPDX text in the appendix.)\n\n");
            missing.extend(spdx_ids(&p.license));
        }
        for (file, text) in &p.texts {
            out.push_str(&format!("[{file}]\n{}\n\n", text));
        }
    }
}

